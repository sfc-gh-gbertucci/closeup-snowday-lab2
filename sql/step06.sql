GRANT DATABASE ROLE CLOSEUP_HOL2.DR_GOLD_READ TO ROLE AGENT_USER_ROLE;

-- Compute: engineers can also resize/resume the warehouse. HOL_ANALYST is deliberately
-- left WITHOUT warehouse usage for now (error b).
